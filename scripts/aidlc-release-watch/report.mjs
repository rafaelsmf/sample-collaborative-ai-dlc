// Renders one release check as a GitHub issue. Only validated values (tag,
// commit, dates) appear as Markdown; upstream file paths are reduced to a safe
// alphabet and shown in a code block, so they cannot mention, link or format.
import { REPOSITORY, SHA_RE, versionOfTag } from './source.mjs';

const MAX_PATHS = 50;
const MAX_BODY = 60_000;

const marker = ({ tag, sha }) =>
  `<!-- aidlc-release-watch:${versionOfTag(tag) ? tag : 'invalid'}@${SHA_RE.test(sha ?? '') ? sha : 'none'} -->`;

const safePath = (value) =>
  String(value)
    .replace(/[^A-Za-z0-9._/+-]/g, '?')
    .slice(0, 200);

// A check detail can carry an error message; keep it to one plain line.
const safeText = (value) =>
  [...String(value)]
    .filter((char) => !/[\p{Cc}\p{Cf}]/u.test(char))
    .join('')
    .replace(/[`<>[\]@|*_]/g, "'")
    .slice(0, 300);

const VERDICTS = {
  'integrity-failed':
    'The source of this release could not be verified. Do not onboard it until the failed checks are understood.',
  verified:
    "The archive of this release is the commit's git tree as GitHub lists it. The platform does not offer it until a reviewed pull request adds its profile.",
  ready:
    "The archive is the commit's git tree, and this build imports the release with no diagnostic and no certification gap the newest supported version does not already have. The platform does not offer it until a reviewed pull request adds its profile.",
  'needs-work':
    "The archive is the commit's git tree, but this build cannot import or certify the release as it is; see the qualification below before onboarding it.",
  'already-supported': 'This commit is already a supported profile; nothing to onboard.',
};

const sourceTable = (result) => {
  const rows = [
    `| Tag | [\`${result.tag}\`](https://github.com/${REPOSITORY}/releases/tag/${result.tag}) |`,
    `| Commit | ${result.sha ? `\`${result.sha}\`` : 'none'} |`,
  ];
  if (result.publishedAt) rows.push(`| Published | ${result.publishedAt} |`);
  rows.push(`| Immutable release | ${result.immutable ? 'yes' : 'no (not enforced by GitHub)'} |`);
  if (result.supportedProfileId) rows.push(`| Supported as | \`${result.supportedProfileId}\` |`);
  return ['| Source | |', '| --- | --- |', ...rows].join('\n');
};

const checkLines = (checks) =>
  checks.flatMap(({ id, ok, detail, paths }) => {
    const line = `- ${ok ? '✅' : '❌'} **${id}**: ${safeText(detail)}`;
    if (!paths?.length) return [line];
    const shown = paths.slice(0, MAX_PATHS).map(safePath);
    const more = paths.length > MAX_PATHS ? [`… and ${paths.length - MAX_PATHS} more`] : [];
    return [
      line,
      '',
      `  <details><summary>${paths.length} files</summary>`,
      '',
      '  ```text',
      ...[...shown, ...more].map((item) => `  ${item}`),
      '  ```',
      '',
      '  </details>',
    ];
  });

const driftLines = (drift) =>
  drift.length === 0
    ? []
    : [
        '',
        '### Supported versions whose tag now names other core/ content',
        '',
        'Installations keep loading the pinned commit; review whether upstream re-tagged these versions.',
        '',
        ...drift.map(({ version, tagSha, changed = [] }) => {
          const files = changed.length
            ? `, which changes ${changed
                .slice(0, 10)
                .map((name) => `\`${safePath(name)}\``)
                .join(', ')}${changed.length > 10 ? ` and ${changed.length - 10} more` : ''}`
            : '';
          return `- ${version}: the tag names ${tagSha ? `\`${tagSha}\`` : 'no commit'}${files}`;
        }),
      ];

const renderReport = ({ result, drift = [], sections = [] }) => {
  const title = `AI-DLC ${result.version}: release qualification report`;
  const body = [
    marker(result),
    `## AI-DLC ${result.version} is available upstream`,
    '',
    `**Verdict: \`${result.verdict}\`.** ${VERDICTS[result.verdict] ?? ''}`.trimEnd(),
    '',
    sourceTable(result),
    '',
    '### Integrity',
    '',
    ...checkLines(result.checks),
    ...driftLines(drift),
    ...sections.flatMap((section) => ['', ...section]),
    '',
    '---',
    '_Generated by `scripts/aidlc-release-watch/check.mjs`. It never changes code, the release registry, channels or a deployment._',
  ].join('\n');
  return {
    title,
    marker: marker(result),
    body: body.length > MAX_BODY ? `${body.slice(0, MAX_BODY)}\n\n_Report truncated._` : body,
  };
};

export { marker, renderReport, safePath };
